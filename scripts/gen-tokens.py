#!/usr/bin/env python3
"""Write client/lib/tokens.g.dart from client/tokens/tokens.json."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent / "client"
tokens = json.loads((root / "tokens" / "tokens.json").read_text())


def color(value):
    hex_ = value.lstrip("#")
    if len(hex_) == 6:
        hex_ += "ff"
    rgb, alpha = hex_[:6], hex_[6:]
    return f"Color(0x{alpha}{rgb})"


def number(value):
    return f"{float(value):g}" if float(value) != int(value) else str(int(value))


def entries(group):
    return [(k, v) for k, v in group.items() if not k.startswith("$")]


out = [
    "// Generated by scripts/gen-tokens.py from client/tokens/tokens.json. Do not edit.",
    "import 'package:flutter/painting.dart';",
    "",
    "/// Accent colors a member can pick, by name.",
    "const accentTokens = <String, Color>{",
]
out += [f"  '{k}': {color(v)}," for k, v in entries(tokens["color"]["accent"])]
out += ["};", ""]
for scheme in ("light", "dark"):
    name = scheme.capitalize() + "Tokens"
    out += [f"/// The {scheme} theme's colors.", f"abstract final class {name} {{"]
    out += [f"  static const {k} = {color(v)};" for k, v in entries(tokens["color"][scheme])]
    out += ["}", ""]
for group, name, doc in (
    ("space", "Space", "Paddings and gaps."),
    ("radius", "Radii", "Corner radii."),
    ("fontSize", "FontSizes", "Type sizes."),
):
    out += [f"/// {doc}", f"abstract final class {name} {{"]
    out += [f"  static const double {k} = {number(v)};" for k, v in entries(tokens[group])]
    out += ["}", ""]
target = root / "lib" / "tokens.g.dart"
text = "\n".join(out).rstrip("\n") + "\n"
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text() == text else "tokens.g.dart is stale: run scripts/gen-tokens.py")
target.write_text(text)
